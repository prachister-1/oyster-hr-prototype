export function initials(name) {
  return name.split(' ').map((p) => p[0]).slice(0, 2).join('')
}

export function colorFor(name) {
  let n = 0
  for (const c of name) n += c.charCodeAt(0)
  return COLORS[n % COLORS.length]
}

